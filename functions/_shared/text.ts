// ============================================================================
// 文字正規化:修正 LLM JSON 輸出常見的「字面 \n」問題
//   模型偶爾會把換行輸出成兩個字元的 "\n"(反斜線 + n),
//   JSON.parse 後仍是字面字元,直接發布就會在貼文上看到 "\n"。
// ============================================================================

/** 把字面上的 \n / \t 轉成真正的換行與空格,並收斂多餘空行 */
export function normalizeMultilineText(text: string): string {
  return text
    .replace(/\\r\\n/g, '\n')
    .replace(/\\n/g, '\n')
    .replace(/\\t/g, ' ')
    .replace(/\n{3,}/g, '\n\n');
}
